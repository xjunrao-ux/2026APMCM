ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "题目与要求/date/Data02_AfricanPenguins_playbacks_data.csv"
CONTRASTS = ROOT / "_q3_analysis/code1_results/Q3_2_Code1_All_Contrasts.csv"
FACTOR_RESULTS = ROOT / "_q3_analysis/behavior_factor_results.json"
OUT = ROOT / "figures"
INK = "#192737"
MUTED = "#566576"
GRID = "#E3E9EF"
CONTROL = "#687786"
NATURAL = "#225D94"
TEAL = "#146F65"
AMBER = "#9A5E1E"
BEHAVIORS = ("抬头", "鸣叫", "靠近")
BEHAVIOR_STYLES = ((NATURAL, "o"), (TEAL, "s"), (AMBER, "^"))
COMBINATION_ORDER = ("No response", "H", "V", "A", "H+V", "H+A", "V+A", "H+V+A")
COMBINATION_LABELS = ("无响应", "仅抬头", "仅鸣叫", "仅靠近",
                      "抬头＋鸣叫", "抬头＋靠近", "鸣叫＋靠近", "三种行为都出现")
MAJOR_COMBINATIONS = ("V", "H+V", "H+V+A")


